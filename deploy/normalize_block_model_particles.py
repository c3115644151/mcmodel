#!/usr/bin/env python3
"""Give atlas-backed block models a compact particle tile cropped from a real face UV."""
from __future__ import annotations

import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
MODEL_ROOT = ROOT / "src/main/resources/assets/pastoral_home/models/block"
REPORT = ROOT / "build/model_particle_audit.json"


def main() -> None:
    models = sorted(MODEL_ROOT.rglob("*.json"))
    changed = []
    for path in models:
        data = json.loads(path.read_text(encoding="utf-8"))
        textures = data.get("textures", {})
        particle = textures.get("particle")
        regular_values = [value for key, value in textures.items()
                          if key != "particle" and isinstance(value, str)
                          and value.startswith("pastoral_home:block/")]
        regular_refs = set(regular_values)
        if not regular_refs:
            continue
        primary = textures.get("bb_texture_0")
        if primary not in regular_refs:
            primary = regular_values[0]

        # Dedicated particles generated by artists/importers are already tiles.
        # Otherwise crop one large face from the atlas; using the whole UV sheet
        # produces random wood/metal/transparent fragments during block breaking.
        particle_is_dedicated = bool(particle and "_particle" in particle.rsplit("/", 1)[-1])
        # A tile this script named is derived, not authoured: it is recomputed on every run, so
        # improving the shaping rule actually reaches the models. Only a particle texture whose name
        # the artist chose is left alone, which is what used to make an improved rule a no-op.
        particle_is_derived = bool(particle) and (particle.rsplit("/", 1)[-1] == path.stem + "_particle")
        particle_matches_atlas = particle in regular_refs
        needs_tile = (particle == "minecraft:block/oak_planks" or particle_is_derived
                      or particle_is_dedicated is False and (particle_matches_atlas or particle is None))
        if not needs_tile:
            continue
        source_file = _texture_path(primary)
        if source_file is None or not source_file.is_file():
            continue
        with Image.open(source_file) as opened:
            atlas = opened.convert("RGBA")
        if not particle_is_dedicated and atlas.size == (16, 16) and particle != "minecraft:block/oak_planks":
            continue
        face = _largest_face(data, textures, primary)
        frame = _frame_height(source_file, atlas)
        crop = _crop_uv(atlas, face, frame) if face else atlas
        if not any(pixel[3] > 127 for pixel in crop.getdata()):
            # A uv window can sit entirely on transparent atlas texels (a chair's back slats are
            # sampled from a gap); the frame behind it still has the model's own colours.
            crop, face = atlas.crop((0, 0, atlas.width, frame or atlas.height)), None
        if not any(pixel[3] > 127 for pixel in crop.getdata()):
            # Nothing painted anywhere in the frame: the artist's particle choice is the only signal
            # left, so leave the model alone instead of shipping a blank tile.
            continue
        tile, how = _tile(crop)
        target_name = f"{path.stem}_particle.png"
        target_file = ROOT / "src/main/resources/assets/pastoral_home/textures/block" / target_name
        target_file.parent.mkdir(parents=True, exist_ok=True)
        if not target_file.is_file() or Image.open(target_file).convert("RGBA").tobytes() != tile.tobytes():
            tile.save(target_file)
        textures["particle"] = f"pastoral_home:block/{target_name.rsplit('.', 1)[0]}"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        changed.append({"model": path.relative_to(MODEL_ROOT).as_posix(), "particle": textures["particle"],
                        "uv": face, "tile": how, "crop": list(crop.size)})

    remaining = []
    for path in models:
        data = json.loads(path.read_text(encoding="utf-8"))
        textures = data.get("textures", {})
        particle = textures.get("particle")
        if particle == "minecraft:block/oak_planks" and any(
                key != "particle" and isinstance(value, str) and value.startswith("pastoral_home:block/")
                for key, value in textures.items()):
            remaining.append(path.relative_to(MODEL_ROOT).as_posix())
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(json.dumps({"models_scanned": len(models), "models_changed": changed,
                                  "remaining_custom_models_with_oak_particle": remaining},
                                 ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if remaining:
        raise SystemExit("Custom block models still use oak-plank particles: " + ", ".join(remaining))
    print(f"Block particles normalized: {len(models)} models scanned, {len(changed)} atlas-backed particle tiles generated.")


def _texture_path(resource: str | None) -> Path | None:
    if not resource or ":" not in resource:
        return None
    namespace, location = resource.split(":", 1)
    if namespace != "pastoral_home" or not location.startswith("block/"):
        return None
    return ROOT / "src/main/resources/assets/pastoral_home/textures" / f"{location}.png"


def _largest_face(model: dict, textures: dict, texture_resource: str):
    key_names = {key for key, value in textures.items() if key != "particle" and value == texture_resource}
    largest = None
    face_priority = {"south": 6, "east": 5, "west": 4, "north": 3, "up": 2, "down": 1}
    for element in model.get("elements", []):
        for face_name, face in element.get("faces", {}).items():
            ref = face.get("texture", "")
            if not isinstance(ref, str) or not ref.startswith("#") or ref[1:] not in key_names:
                continue
            uv = face.get("uv")
            if not isinstance(uv, list) or len(uv) != 4:
                continue
            area = abs(float(uv[2]) - float(uv[0])) * abs(float(uv[3]) - float(uv[1]))
            score = (area, face_priority.get(face_name, 0))
            if area > 0 and (largest is None or score > largest[0]):
                largest = (score, uv)
    return largest[1] if largest else None


def _frame_height(texture_file: Path, atlas: Image.Image) -> int | None:
    """Height of one frame of an animated sheet, or None for a still image.

    Minecraft stacks animation frames as squares: the frame is atlas.width tall, so a 32x128 strip is
    four frames and a uv rect covers one. Scaling v by atlas.height/16 spreads one face over all four
    frames, which is why breaking an animated block rained unrelated fragments.
    """
    meta_file = Path(str(texture_file) + ".mcmeta")
    if not meta_file.is_file():
        return None
    try:
        meta = json.loads(meta_file.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        return None
    if "animation" not in meta or atlas.width >= atlas.height:
        return None
    return atlas.width


def _crop_uv(atlas: Image.Image, uv: list[float], frame: int | None = None) -> Image.Image:
    scale_x = atlas.width / 16.0
    scale_y = (frame or atlas.height) / 16.0
    x0 = max(0, min(atlas.width, round(min(float(uv[0]), float(uv[2])) * scale_x)))
    x1 = max(0, min(atlas.width, round(max(float(uv[0]), float(uv[2])) * scale_x)))
    y0 = max(0, min(frame or atlas.height, round(min(float(uv[1]), float(uv[3])) * scale_y)))
    y1 = max(0, min(frame or atlas.height, round(max(float(uv[1]), float(uv[3])) * scale_y)))
    return atlas.crop((x0, y0, x1, y1)) if x1 > x0 and y1 > y0 else atlas


def _tile(crop: Image.Image):
    """A 16x16 damage tile that keeps the artist's texel scale.

    Resampling a small face window up to 16x16 turns a four-texel paint block into a staircase, which
    is what the party light rained when it broke. A window at least 16x16 is centre-cropped at 1:1 so
    grain survives; anything smaller is flat paint in the window's own dominant colour.
    """
    if crop.size[0] >= 16 and crop.size[1] >= 16:
        left = (crop.size[0] - 16) // 2
        top = (crop.size[1] - 16) // 2
        return crop.crop((left, top, left + 16, top + 16)), "crop"
    counts = {}
    for pixel in crop.getdata():
        if pixel[3] > 127:
            counts[pixel[:3]] = counts.get(pixel[:3], 0) + 1
    if not counts:
        return crop, "empty"
    colour = max(counts.items(), key=lambda item: item[1])[0]
    return Image.new("RGBA", (16, 16), (colour[0], colour[1], colour[2], 255)), "flat"


if __name__ == "__main__":
    main()
