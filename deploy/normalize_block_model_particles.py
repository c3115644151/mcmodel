#!/usr/bin/env python3
"""Give atlas-backed block models a compact particle tile cropped from a real face UV."""
from __future__ import annotations

import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
MODEL_ROOT = ROOT / "src/main/resources/assets/pastoral_home/models/block"
REPORT = ROOT / "build/model_particle_audit.json"


def main() -> None:
    models = sorted(MODEL_ROOT.rglob("*.json"))
    changed = []
    for path in models:
        data = json.loads(path.read_text(encoding="utf-8"))
        textures = data.get("textures", {})
        particle = textures.get("particle")
        regular_values = [value for key, value in textures.items()
                          if key != "particle" and isinstance(value, str)
                          and value.startswith("pastoral_home:block/")]
        regular_refs = set(regular_values)
        if not regular_refs:
            continue
        primary = textures.get("bb_texture_0")
        if primary not in regular_refs:
            primary = regular_values[0]

        # Dedicated particles generated by artists/importers are already tiles.
        # Otherwise crop one large face from the atlas; using the whole UV sheet
        # produces random wood/metal/transparent fragments during block breaking.
        particle_file = _texture_path(particle)
        particle_is_dedicated = bool(particle and "_particle" in particle.rsplit("/", 1)[-1])
        particle_matches_atlas = particle in regular_refs
        needs_tile = (particle == "minecraft:block/oak_planks" or particle_is_dedicated is False
                      and (particle_matches_atlas or particle is None))
        if not needs_tile:
            continue
        source_file = _texture_path(primary)
        if source_file is None or not source_file.is_file():
            continue
        with Image.open(source_file) as opened:
            atlas = opened.convert("RGBA")
        if not particle_is_dedicated and atlas.size == (16, 16) and particle != "minecraft:block/oak_planks":
            continue
        face = _largest_face(data, textures, primary)
        crop = _crop_uv(atlas, face) if face else atlas
        tile = crop.resize((16, 16), Image.Resampling.NEAREST)
        target_name = f"{path.stem}_particle.png"
        target_file = ROOT / "src/main/resources/assets/pastoral_home/textures/block" / target_name
        target_file.parent.mkdir(parents=True, exist_ok=True)
        tile.save(target_file)
        textures["particle"] = f"pastoral_home:block/{Path(target_name).stem}"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        changed.append({"model": path.relative_to(MODEL_ROOT).as_posix(), "particle": textures["particle"],
                        "uv": face})

    remaining = []
    for path in models:
        data = json.loads(path.read_text(encoding="utf-8"))
        textures = data.get("textures", {})
        particle = textures.get("particle")
        if particle == "minecraft:block/oak_planks" and any(
                key != "particle" and isinstance(value, str) and value.startswith("pastoral_home:block/")
                for key, value in textures.items()):
            remaining.append(path.relative_to(MODEL_ROOT).as_posix())
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(json.dumps({"models_scanned": len(models), "models_changed": changed,
                                  "remaining_custom_models_with_oak_particle": remaining},
                                 ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if remaining:
        raise SystemExit("Custom block models still use oak-plank particles: " + ", ".join(remaining))
    print(f"Block particles normalized: {len(models)} models scanned, {len(changed)} atlas-backed particle tiles generated.")


def _texture_path(resource: str | None) -> Path | None:
    if not resource or ":" not in resource:
        return None
    namespace, location = resource.split(":", 1)
    if namespace != "pastoral_home" or not location.startswith("block/"):
        return None
    return ROOT / "src/main/resources/assets/pastoral_home/textures" / f"{location}.png"


def _largest_face(model: dict, textures: dict, texture_resource: str):
    key_names = {key for key, value in textures.items() if key != "particle" and value == texture_resource}
    largest = None
    face_priority = {"south": 6, "east": 5, "west": 4, "north": 3, "up": 2, "down": 1}
    for element in model.get("elements", []):
        for face_name, face in element.get("faces", {}).items():
            ref = face.get("texture", "")
            if not isinstance(ref, str) or not ref.startswith("#") or ref[1:] not in key_names:
                continue
            uv = face.get("uv")
            if not isinstance(uv, list) or len(uv) != 4:
                continue
            area = abs(float(uv[2]) - float(uv[0])) * abs(float(uv[3]) - float(uv[1]))
            score = (area, face_priority.get(face_name, 0))
            if area > 0 and (largest is None or score > largest[0]):
                largest = (score, uv)
    return largest[1] if largest else None


def _crop_uv(atlas: Image.Image, uv: list[float]) -> Image.Image:
    x0 = max(0, min(atlas.width, round(min(float(uv[0]), float(uv[2])) * atlas.width / 16.0)))
    x1 = max(0, min(atlas.width, round(max(float(uv[0]), float(uv[2])) * atlas.width / 16.0)))
    y0 = max(0, min(atlas.height, round(min(float(uv[1]), float(uv[3])) * atlas.height / 16.0)))
    y1 = max(0, min(atlas.height, round(max(float(uv[1]), float(uv[3])) * atlas.height / 16.0)))
    return atlas.crop((x0, y0, x1, y1)) if x1 > x0 and y1 > y0 else atlas


if __name__ == "__main__":
    main()
