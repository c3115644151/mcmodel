#!/usr/bin/env python3
"""Import the potted spruce and split visible geometry into three world cells."""
from __future__ import annotations

import copy
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "src/main/resources/assets/pastoral_home"
SOURCE = ROOT / "tools/deploy/model_sources/spruce_planter.bbmodel"
BUILD = ROOT / "build/requested_models/spruce_planter"
IMPORTER = ROOT / "tools/deploy/import_java_block_bbmodel.py"
ICON_DIR = ASSETS / "models/item_icons/spruce_planter"


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def save(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def shift_y(model: dict, amount: float) -> dict:
    result = copy.deepcopy(model)
    for element in result.get("elements", []):
        for point in ("from", "to"):
            element[point][1] = float(element[point][1]) + amount
        if "origin" in element:
            element["origin"][1] = float(element["origin"][1]) + amount
        if element.get("rotation") and element["rotation"].get("origin"):
            element["rotation"]["origin"][1] = float(element["rotation"]["origin"][1]) + amount
    return result


def model_bounds(model: dict):
    coords = [float(element[point][axis]) for element in model.get("elements", [])
              for point in ("from", "to") for axis in range(3)]
    if not coords:
        return None
    return tuple(min(float(e[p][a]) for e in model["elements"] for p in ("from", "to"))
                 for a in range(3)) + \
           tuple(max(float(e[p][a]) for e in model["elements"] for p in ("from", "to"))
                 for a in range(3))


def split_cells(placed: dict):
    cells = {0: [], 1: [], 2: []}
    for source_index, element in enumerate(placed.get("elements", [])):
        y0, y1 = sorted((float(element["from"][1]), float(element["to"][1])))
        midpoint = (y0 + y1) * 0.5
        layer = max(0, min(2, int(midpoint // 16.0)))
        fragment = copy.deepcopy(element)
        offset = -16.0 * layer
        for point in ("from", "to"):
            fragment[point][1] = round(float(fragment[point][1]) + offset, 6)
        if "origin" in fragment:
            fragment["origin"][1] = round(float(fragment["origin"][1]) + offset, 6)
        if fragment.get("rotation") and fragment["rotation"].get("origin"):
            fragment["rotation"]["origin"][1] = round(float(fragment["rotation"]["origin"][1]) + offset, 6)
        local_min_y = min(float(fragment["from"][1]), float(fragment["to"][1]))
        local_max_y = max(float(fragment["from"][1]), float(fragment["to"][1]))
        if local_min_y < -16.0001 or local_max_y > 32.0001:
            raise ValueError(f"Source element {source_index} cannot fit in a single Minecraft model segment")
        fragment["_source_index"] = source_index
        cells[layer].append(fragment)
    return cells


def blockstates():
    multipart = []
    for facing, angle in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
        for layer in range(3):
            state = {"model": f"pastoral_home:block/spruce_planter_l{layer}"}
            if angle:
                state["y"] = angle
            multipart.append({"when": {"facing": facing, "layer": str(layer)}, "apply": state})
    return {"multipart": multipart}


def item_definition():
    model = "pastoral_home:block/spruce_planter_item"
    return {"model": {
        "type": "minecraft:select",
        "property": "minecraft:display_context",
        "cases": [{"when": "gui", "model": {"type": "minecraft:model", "model": model}}],
        "fallback": {"type": "minecraft:model", "model": model},
    }}


def update_generated_support_data() -> None:
    generated = ROOT / "src/generated/resources"
    for locale, display_name in (("en_us", "Small Potted Spruce"), ("zh_cn", "小云杉盆栽")):
        path = generated / f"assets/pastoral_home/lang/{locale}.json"
        document = load(path)
        document["block.pastoral_home.spruce_planter"] = display_name
        save(path, document)

    # The anchor-only loot table is generated by ModBlockLootProvider; a second copy here would be
    # one more place to forget when the anchor cell moves.

    axe_tag_path = generated / "data/minecraft/tags/block/mineable/axe.json"
    axe_tag = load(axe_tag_path)
    values = axe_tag.setdefault("values", [])
    if "pastoral_home:spruce_planter" not in values:
        values.append("pastoral_home:spruce_planter")
    save(axe_tag_path, axe_tag)


def main() -> None:
    if not SOURCE.is_file():
        raise FileNotFoundError(f"Missing authored spruce planter source: {SOURCE}")
    raw_path = BUILD / "spruce_planter_raw.json"
    texture_path = ASSETS / "textures/block/spruce_planter.png"
    subprocess.run([
        sys.executable, str(IMPORTER), str(SOURCE), "--model-out", str(raw_path),
        "--texture-out", str(texture_path), "--texture-name", "spruce_planter",
    ], cwd=ROOT, check=True)
    raw = load(raw_path)
    if len(raw.get("elements", [])) != 19:
        raise ValueError(f"Expected 19 authored planter/tree cubes; got {len(raw.get('elements', []))}")
    placed = shift_y(raw, 16.0)
    save(BUILD / "spruce_planter_placed_world.json", placed)
    world_bounds = model_bounds(placed)
    # Only y is fixed by placement; x/z remain as the artist authored them.
    if world_bounds is None or abs(world_bounds[1]) > 0.02 or abs(world_bounds[4] - 48.0) > 0.02:
        raise ValueError(f"Potted spruce should sit at y=0 and reach exactly 3 cells: {world_bounds}")
    cells = split_cells(placed)
    expected_elements = len(placed["elements"])
    if sum(len(values) for values in cells.values()) != expected_elements or any(not cells[i] for i in range(3)):
        raise ValueError("Every source cube must appear exactly once across the three visible layers")
    manifest = {str(layer): [int(element["_source_index"]) for element in elements]
                for layer, elements in cells.items()}
    save(BUILD / "spruce_planter_split_manifest.json", manifest)

    model_dir = ASSETS / "models/block"
    for layer, elements in cells.items():
        model = copy.deepcopy(placed)
        model["elements"] = [{key: value for key, value in e.items() if key != "_source_index"} for e in elements]
        save(model_dir / f"spruce_planter_l{layer}.json", model)
    # Items render the authored complete model with its hand/ground transforms;
    # only their GUI branch is replaced with a normalized one-cell proxy below.
    save(model_dir / "spruce_planter_item.json", raw)
    save(ASSETS / "blockstates/spruce_planter.json", blockstates())
    save(ASSETS / "items/spruce_planter.json", item_definition())
    update_generated_support_data()
    print("Prepared the potted spruce as 3 cell-owned models; source geometry and UVs are preserved.")


if __name__ == "__main__":
    main()
